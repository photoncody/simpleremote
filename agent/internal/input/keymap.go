package input

// k builds a Key. mac < 0 means the key has no macOS equivalent.
func k(code string, win, evdev uint16, mac int) Key {
	key := Key{Code: code, Win: win, Evdev: evdev}
	if mac >= 0 {
		key.Mac, key.HasMac = uint16(mac), true
	}
	return key
}

